#!/usr/bin/env python3
"""Erzeugt src/dwd_stations.h: alle MOSMIX-Stationen des DWD (Kennung, Lage, Name) und ob es
für die Station stündliche Messwerte gibt (opendata.dwd.de/weather/weather_reports/poi/).

  python3 tools/gen_dwd_stations.py            # lädt ~37 MB (MOSMIX_S, alle Stationen)

Quelle: Deutscher Wetterdienst, Open Data (Daten frei, Quellenangabe "DWD").
"""
import io, re, sys, urllib.request, zipfile

MOS = "https://opendata.dwd.de/weather/local_forecasts/mos/MOSMIX_S/all_stations/kml/MOSMIX_S_LATEST_240.kmz"
POI = "https://opendata.dwd.de/weather/weather_reports/poi/"

def get(url):
    with urllib.request.urlopen(url, timeout=300) as r:
        return r.read()

def main(out="src/dwd_stations.h"):
    poi = set(re.findall(r'href="([^"]+)-BEOB\.csv"', get(POI).decode("latin1")))
    z = zipfile.ZipFile(io.BytesIO(get(MOS)))
    st, cur = [], {}
    with z.open(z.namelist()[0]) as f:
        for line in io.TextIOWrapper(f, encoding="latin1"):
            m = re.search(r"<kml:name>([^<]*)", line)
            if m: cur = {"id": m.group(1)}; continue
            m = re.search(r"<kml:description>([^<]*)", line)
            if m: cur["name"] = m.group(1); continue
            m = re.search(r"<kml:coordinates>([^<]*)", line)
            if m:
                lon, lat, _ = m.group(1).split(",")
                cur["lat"], cur["lon"] = float(lat), float(lon)
                st.append(cur)
    names, offs = bytearray(), []
    for s in st:
        offs.append(len(names))
        names += s.get("name", "").encode("latin1", "replace")[:24].replace(b'"', b"'") + b"\0"
    rows = []
    for s, o in zip(st, offs):
        rows.append('{"%s",%d,%d,%d,%d}' % (s["id"][:5], round(s["lat"] * 100), round(s["lon"] * 100),
                                            o, 1 if s["id"] in poi else 0))
    def cstr(b):
        return "".join("\\%03o" % c if c < 32 or c > 126 or c in (34, 92, 63) else chr(c) for c in b)
    with open(out, "w") as f:
        f.write("// Auto-generated by tools/gen_dwd_stations.py -- DO NOT EDIT.\n")
        f.write("// DWD MOSMIX stations (Quelle: Deutscher Wetterdienst, Open Data). %d stations, %d with\n" % (len(st), sum(1 for s in st if s["id"] in poi)))
        f.write("// hourly observations (obs=1). lat/lon in 1/100 degree; name = offset into DWD_STATION_NAMES.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("struct DwdStation { char id[6]; int16_t lat; int16_t lon; uint32_t name; uint8_t obs; };\n\n")
        f.write("static const int DWD_STATION_COUNT = %d;\n" % len(st))
        f.write("static const DwdStation DWD_STATIONS[DWD_STATION_COUNT] = {\n")
        for i in range(0, len(rows), 6):
            f.write("  " + ",".join(rows[i:i + 6]) + ",\n")
        f.write("};\n\nstatic const char DWD_STATION_NAMES[] =\n")
        for i in range(0, len(names), 96):
            f.write('  "%s"\n' % cstr(bytes(names[i:i + 96])))
        f.write(";\n")
    print("wrote", out, len(st), "stations")

if __name__ == "__main__":
    main(*sys.argv[1:])
